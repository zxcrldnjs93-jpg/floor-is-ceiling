import { readFile, writeFile } from "node:fs/promises";

const design = new URL("../../design/final/", import.meta.url);
const output = new URL("./card-design.js", import.meta.url);
const read = file => readFile(new URL(file, design), "utf8");

const [tokens, base, css, section, card] = await Promise.all([
  read("tokens.css"), read("base.css"), read("card.css"), read("section.js"), read("card.js"),
]);
const indent = source => source.trimEnd().split("\n").map(line => line ? `  ${line}` : "").join("\n");
const styles = [tokens, base, css].map(sheet => indent(sheet.trimEnd().split("\n").map(line => `${JSON.stringify(line)},`).join("\n")));
const generated = `// Generated by sync-card-design.mjs from design/final.\n` +
  `export const cardStyles = [\n${styles.join('\n  "",\n')}\n].join("\\n");\n\n` +
  `export function renderDesignCard(document, root, data) {\n  const window = {};\n` +
  `${indent(section)}\n${indent(card)}\n  return window.UpstairsCard.render(root, data);\n}\n`;

if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8").catch(() => "") !== generated) {
    console.error("카드 디자인 모듈을 동기화하세요: node proto/fx/sync-card-design.mjs");
    process.exitCode = 1;
  }
} else {
  await writeFile(output, generated);
}
